--- МІСТОК ДО ПЛАТФОРМНОГО SDK: мітки фаз назовні й команди всередину.
---
--- НАВІЩО. Заміряти веб-збірку ззовні майже нічим: `print` із Lua у вебі не
--- видно взагалі, екранний профайлер вирізано з релізного рушія, а мережа
--- відповідає лише на питання «скільки байтів». На живому 0.21 мережа
--- закінчується на 13 секунді, а смуга завантаження через дві хвилини показує
--- 24 % — тобто найдорожче саме те, чого жоден зовнішній інструмент не бачить.
--- Гра мусить сама сказати, де вона.
---
--- ЩО ЦЕ ЗАМІНЮЄ. Раніше кожна гра мала власний `perf.lua`, який складав JS
--- руками й тримав власний масив міток. Тепер усі кличуть один SDK, тож канал і
--- формат спільні, а час ставить SDK — на одному годиннику з мережею.
---
--- ЧАС СТАВИТЬ НЕ ЦЕЙ ФАЙЛ. Ми лише кажемо «сталось», а `performance.now()`
--- бере SDK у документі гри. Зводити два годинники не треба, і не можна:
--- панель живе в іншому документі з іншим `timeOrigin`.
---
--- НІЩО ТУТ НЕ МАЄ ПРАВА ЗРОНИТИ ГРУ. Якщо SDK на сторінці немає — кожен
--- виклик тихо нічого не робить. Якщо це не веб-збірка — так само.
---
--- ВСТАНОВЛЕННЯ. Покласти файл у проєкт і викликати у кількох місцях:
---
---     local filbert = require("filbert.filbert")
---     filbert.ready()             -- рушій піднявся, наш код виконується
---     filbert.loading_finished()  -- перший екран видно й можна торкатись
---     filbert.gameplay_start()    -- почалась гра
---     filbert.phase("level_3")    -- будь-яка своя віха

local M = {}

--- `html5` існує лише у веб-збірці; на десктопі місток друкує, і там це видно.
local web = html5 ~= nil

--- Має збігатися з `bridgeName` у `attachDefold`.
local BRIDGE = "__filbert"

--- Екранування імені для однолапкового JS-рядка.
---
--- Не косметика: старий `perf.lua` склеював ім'я в літерал без обробки, і
--- апостроф або зворотний слеш у назві ламав вираз цілком — мітка зникала
--- мовчки. Тут імена приходять із різних ігор, тож на везіння покладатись не
--- можна. Переведення рядка теж прибираємо: воно обриває вираз.
local function escape(value)
	local text = tostring(value or "")
	text = text:gsub("\\", "\\\\")
	text = text:gsub("'", "\\'")
	text = text:gsub("[\r\n]", " ")
	return text
end

--- Покликати метод містка й повернути рядок (або "" — ніколи nil).
---
--- `window.__filbert && ...` — не перестраховка: збірка без SDK на сторінці
--- мусить працювати як завжди, а не падати на першій же мітці.
local function call(method, argument)
	if not web then
		print("[filbert] " .. method .. " " .. tostring(argument or ""))
		return ""
	end
	local inner
	if argument == nil then
		inner = "window." .. BRIDGE .. "." .. method .. "()"
	else
		inner = "window." .. BRIDGE .. "." .. method .. "('" .. escape(argument) .. "')"
	end
	local ok, result = pcall(html5.run,
		"(window." .. BRIDGE .. " && " .. inner .. ") || ''")
	if ok and result then
		return result
	end
	return ""
end

--- Рушій піднявся й наш код виконується. Один раз за сеанс.
function M.ready()
	call("ready")
end

--- Гра готова до взаємодії — перший екран. Один раз за сеанс.
---
--- Саме цього SDK НЕ вгадує з прогресу завантажувача: той каже «ассети
--- скачано», а метрика означає «гравець бачить і може торкнутись». У цій грі
--- між цими двома подіями хвилини.
function M.loading_finished()
	call("loadingFinished")
end

--- Почалась гра. Саме від цієї точки портали міряють трафік.
function M.gameplay_start()
	call("gameplayStart")
end

function M.gameplay_stop()
	call("gameplayStop")
end

--- Довільна віха: menu, lobby, level_loaded.
function M.phase(name)
	call("phase", name)
end

--- Забрати чергову команду ззовні, або nil.
---
--- Читання одразу ж її і стирає: інакше команда виконувалась би щоразу, поки
--- панель не перезапише поле, а вона цього робити не зобов'язана.
function M.take_command()
	local command = call("cmd")
	if command ~= "" then
		return command
	end
	return nil
end

return M
